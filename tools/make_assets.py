for y, r in enumerate(rows):
    assert len(r) == MW, f"row {y} length {len(r)}"
    for x, c in enumerate(r):
        if c == 'P':
            start = (x + 0.5, y + 0.5); grid.append(0)
        elif c == 'e':
            enemies.append((x + 0.5, y + 0.5)); grid.append(0)
        elif c == 'D':
            grid.append(5)
        elif c == '.':
            grid.append(0)
        else:
            grid.append(int(c))

