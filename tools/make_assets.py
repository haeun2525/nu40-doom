def pack2bit(art, w, h):
    """2비트/픽셀, 가로 우선. 한 바이트에 픽셀 4개."""
    rows = art.split("\n")
    assert len(rows) == h, f"height {len(rows)} != {h}"
    bits = []
    for y in range(h):
        r = rows[y].ljust(w)
        assert len(r) == w, f"width {len(r)} != {w}"
        for x in range(w):
            bits.append(LV[r[x]])
    while len(bits) % 4:            # 4의 배수가 아니면 뒤를 0으로 채운다
        bits.append(0)
    out = bytearray()
    for i in range(0, len(bits), 4):
        out.append(bits[i] | bits[i+1] << 2 | bits[i+2] << 4 | bits[i+3] << 6)
    return out

def carr(name, data, per=16):
    s = f"static const uint8_t {name}[{len(data)}] = {{\n"
    for i in range(0, len(data), per):
        s += "  " + ",".join(f"0x{b:02x}" for b in data[i:i+per]) + ",\n"
    return s + "};\n"

